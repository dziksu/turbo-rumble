export type Message = keyof typeof EN;
export type Language = 'en' | 'pl';
export const languageLocale = (language: Language) => (language === 'pl' ? 'pl-PL' : 'en-GB');
export type Values = Readonly<Record<string, string | number>>;
export function parseLanguage(value: unknown): Language {
  return value === 'pl' ? 'pl' : 'en';
}
export function translate(message: string, language: Language, values: Values = {}): string {
  const template =
    language === 'en' && Object.hasOwn(EN, message) ? EN[message as Message] : message;
  // Replacements are inserted once: names containing braces must remain literal.
  return template.replace(/\{(\w+)\}/g, (token, key: string) =>
    Object.hasOwn(values, key) ? String(values[key]) : token,
  );
}
